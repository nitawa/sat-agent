"""Assembler node: Generates a build_result.sh convenience wrapper around the
reproducible Dockerfile that graph.py has been accumulating stage-by-stage.

The Dockerfile (not this script) is the source of truth for how the build is
reproduced: every stage command the agent actually ran and verified was
baked into it as a RUN step (see docker_manager.py: add_stage_run). This
script is just `docker build && docker run` convenience wrapping that.
"""

from pathlib import Path


def assemble_build_result(state: dict, work_dir: Path) -> dict:
    stages = state.get("stages", {})
    run_id = state.get("run_id", "run")
    image_tag = f"sat_build_{run_id}".lower()

    work_dir.mkdir(parents=True, exist_ok=True)
    script_path = work_dir / "build_result.sh"

    lines = [
        "#!/usr/bin/env bash",
        "# Reproducible build wrapper generated by sat-agent.",
        "# The Dockerfile alongside this script is the actual, step-by-step",
        "# build recipe (every RUN line is a stage command that was executed",
        "# and verified by the agent) -- this just builds and runs it.",
        f"# Run ID: {run_id}",
        f"# Original Prompt: {state.get('user_request', '')}",
        "set -e",
        "",
        'SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"',
        "",
        "echo '=== Building SALOME SAT image from the recorded Dockerfile ==='",
        f'docker build -t {image_tag} -f "$SCRIPT_DIR/Dockerfile" "$SCRIPT_DIR"',
        "",
        "echo '=== Stages baked into this build ==='",
    ]

    for idx, stage in sorted(stages.items()):
        cmd = stage.get("command_script")
        if cmd:
            lines.append(f"# Stage {idx + 1} [{stage.get('module')}]: {cmd}")

    lines += [
        "",
        f'docker run --rm -it -v "$SCRIPT_DIR/BUILD_STATE:{"/salome_build"}" {image_tag} bash',
        "",
        "echo '=== SALOME SAT Build Completed Successfully ==='",
    ]

    script_content = "\n".join(lines)
    script_path.write_text(script_content, encoding="utf-8")
    script_path.chmod(0o755)

    return {
        "final_script": str(script_path),
        "final_script_content": script_content,
    }
