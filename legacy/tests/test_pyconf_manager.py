from pathlib import Path
import tempfile
from sat_agent.pyconf_manager import PyconfManager, read_system_deps_cache, write_system_deps_cache


def test_pyconf_add_product():
    with tempfile.TemporaryDirectory() as tmpdir:
        conf_file = Path(tmpdir) / "test_app.conf"
        mgr = PyconfManager(conf_file)

        mgr.add_or_update_product("SLACKWARE_PRODUCT", {
            "name": "SLACKWARE_PRODUCT",
            "build_source": "git",
            "get_source": "git",
        })

        saved_file = mgr.save()
        assert saved_file.exists()

        content = saved_file.read_text(encoding="utf-8")
        assert "SLACKWARE_PRODUCT" in content
        assert "PRODUCTS" in content


def test_write_product_file_uses_real_pyconf_dsl():
    with tempfile.TemporaryDirectory() as tmpdir:
        product_path = Path(tmpdir) / "GEOM.pyconf"
        PyconfManager.write_product_file(product_path, {
            "name": "GEOM",
            "build_source": "cmake",
            "source_dir": "$APPLICATION.workdir + $VARS.sep + 'SOURCES' + $VARS.sep + $name",
            "depend": ["KERNEL", "GUI"],
            "patches": [],
        })
        content = product_path.read_text(encoding="utf-8")

        assert content.startswith("# Generated by sat-agent")
        assert "default : {" in content
        # unquoted bare keys, pyconf ':' separator -- not Python dict repr
        assert "name : 'GEOM'" in content
        assert "'name':" not in content
        # raw pyconf expressions are emitted unquoted, not as a Python string literal
        assert "source_dir : $APPLICATION.workdir + $VARS.sep + 'SOURCES' + $VARS.sep + $name" in content
        assert "depend : ['KERNEL', 'GUI']" in content
        assert "patches : []" in content


def test_write_application_file_products_use_bare_keys_for_default_version():
    with tempfile.TemporaryDirectory() as tmpdir:
        app_path = Path(tmpdir) / "SALOME-9.12.0.pyconf"
        PyconfManager.write_application_file(app_path, {
            "name": "SALOME-9.12.0",
            "workdir": "$LOCAL.workdir + $VARS.sep + $APPLICATION.name + '-' + $VARS.dist",
            "python3": "yes",
            "products": {"GEOM": None, "SMESH": None},
        })
        content = app_path.read_text(encoding="utf-8")

        assert "APPLICATION : {" in content
        assert "workdir : $LOCAL.workdir + $VARS.sep + $APPLICATION.name + '-' + $VARS.dist" in content
        # a None-valued product entry is a bare key, no ':' -- meaning
        # "use this product's default section", matching real SAT_SALOME
        # application files (see applications/SALOME-9.12.0.pyconf).
        assert "'GEOM'" in content
        assert "'GEOM' :" not in content


def test_set_block_key_replaces_existing_value_in_place():
    with tempfile.TemporaryDirectory() as tmpdir:
        app_path = Path(tmpdir) / "SALOME-9.16.0-native.pyconf"
        app_path.write_text(
            "APPLICATION :\n{\n    name : 'SALOME-9.16.0-native'\n"
            "    properties :\n    {\n        mesa_launcher_in_package : \"yes\"\n"
            "        git_server : 'tuleap'\n        pip : 'yes'\n    }\n"
            "    products :\n    {\n        'GEOM'\n    }\n}\n",
            encoding="utf-8",
        )

        PyconfManager.set_block_key(app_path, "properties", "git_server", "github")
        content = app_path.read_text(encoding="utf-8")

        assert "git_server : 'github'" in content
        assert "'tuleap'" not in content
        # everything else in the file (including outside the properties block) untouched
        assert "mesa_launcher_in_package : \"yes\"" in content
        assert "pip : 'yes'" in content
        assert "'GEOM'" in content


