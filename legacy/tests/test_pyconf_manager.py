def test_system_deps_cache_round_trips():
    with tempfile.TemporaryDirectory() as tmpdir:
        cache_path = Path(tmpdir) / "system_deps.pyconf"

        write_system_deps_cache(cache_path, {
            "arch": {"eigen3": "eigen", "libfreeimage3": "freeimage"},
            "slackware": {"libproj-dev": "proj"},
        })

        loaded = read_system_deps_cache(cache_path)
        assert loaded == {
            "arch": {"eigen3": "eigen", "libfreeimage3": "freeimage"},
            "slackware": {"libproj-dev": "proj"},
        }


def test_system_deps_cache_missing_file_returns_empty_dict():
    assert read_system_deps_cache(Path("/does/not/exist/system_deps.pyconf")) == {}


def test_system_deps_cache_handles_hyphenated_and_dotted_names():
    # Real package names (Debian and resolved) are always simple identifiers
    # (letters/digits/hyphens/dots/underscores) -- never quotes or
    # backslashes, so the round trip only needs to be exact for those.
    with tempfile.TemporaryDirectory() as tmpdir:
        cache_path = Path(tmpdir) / "system_deps.pyconf"
        write_system_deps_cache(cache_path, {"arch": {"libgl1-mesa-dev": "mesa", "python3.11-dev": "python"}})
        loaded = read_system_deps_cache(cache_path)
        assert loaded == {"arch": {"libgl1-mesa-dev": "mesa", "python3.11-dev": "python"}}


