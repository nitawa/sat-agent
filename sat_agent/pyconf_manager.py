"""PyconfManager: Programmatic parser, editor, and serializer for SAT .pyconf / .conf files."""

from pathlib import Path
import pprint
import re
import typing


def _pyconf_text(value: typing.Any, indent: int = 0) -> str:
    """Renders a Python value as text in SAT's own pyconf DSL (src/pyconf.py),
    e.g. `name : 'GEOM'` with unquoted keys -- NOT Python/JSON dict syntax.

    A string value starting with '$' is emitted as-is (a raw pyconf
    expression such as `$APPLICATION.workdir + $VARS.sep + 'SOURCES'`,
    or a variable reference like `$VARS.sep`), since that is how pyconf
    interpolation and concatenation are written. Any other string is
    quoted as a literal.
    """
    pad = "  " * indent
    inner_pad = "  " * (indent + 1)
    if isinstance(value, dict):
        if not value:
            return "{}"
        lines = ["{"]
        for k, v in value.items():
            if v is None:
                # A bare key with no explicit value -- e.g. in
                # APPLICATION.products, this tells `sat` to use a product's
                # `default` section instead of pinning a version/section.
                lines.append(f"{inner_pad}'{k}'")
            else:
                lines.append(f"{inner_pad}{k} : {_pyconf_text(v, indent + 1)}")
        lines.append(f"{pad}}}")
        return "\n".join(lines)
    if isinstance(value, (list, tuple)):
        if not value:
            return "[]"
        items = ", ".join(_pyconf_text(v, indent) for v in value)
        return f"[{items}]"
    if isinstance(value, bool):
        return "'yes'" if value else "'no'"
    if isinstance(value, str):
        if value.startswith("$"):
            return value
        return "'" + value.replace("'", "\\'") + "'"
    if value is None:
        return "None"
    return str(value)


class PyconfManager:
    """Parses and updates SAT application and product pyconf files."""

    def __init__(self, conf_path: Path):
        self.conf_path = conf_path
        self.config_dict = self._load()

    def _load(self) -> dict:
        if not self.conf_path.exists():
            return {"APPLICATION": {"name": self.conf_path.stem, "products": []}, "PRODUCTS": {}}
        namespace: dict[str, typing.Any] = {}
        with open(self.conf_path, "r", encoding="utf-8") as f:
            exec(f.read(), namespace)
        return {k: v for k, v in namespace.items() if not k.startswith("__")}

    def add_or_update_product(self, product_name: str, spec: dict) -> None:
        """Adds a new product definition or updates an existing product in pyconf."""
        if "PRODUCTS" not in self.config_dict or not isinstance(self.config_dict["PRODUCTS"], dict):
            self.config_dict["PRODUCTS"] = {}
        self.config_dict["PRODUCTS"][product_name] = spec

        if "APPLICATION" in self.config_dict and isinstance(self.config_dict["APPLICATION"], dict):
            products = self.config_dict["APPLICATION"].setdefault("products", [])
            if product_name not in products:
                products.append(product_name)

    def set_app_option(self, key: str, value: typing.Any) -> None:
        """Sets global option in the APPLICATION section."""
        if "APPLICATION" not in self.config_dict:
            self.config_dict["APPLICATION"] = {}
        self.config_dict["APPLICATION"][key] = value

    def save(self, target_path: Path | None = None) -> Path:
        """Writes formatted pyconf dictionary back to disk."""
        target = target_path or self.conf_path
        target.parent.mkdir(parents=True, exist_ok=True)
        with open(target, "w", encoding="utf-8") as f:
            f.write("# Generated by sat-agent\n\n")
            for key, val in self.config_dict.items():
                f.write(f"{key} = {pprint.pformat(val, indent=2)}\n\n")
        return target

    @staticmethod
    def write_product_file(path: Path, spec: dict) -> Path:
        """Writes a standalone SAT_SALOME product pyconf file.

        Real product files (e.g. SAT_SALOME/products/GEOM.pyconf) declare a
        top-level `default : { ... }` block, not a `PRODUCTS = {...}` dict --
        that dict only exists as an in-memory aggregate inside `sat` itself,
        one file per product on disk.
        """
        path.parent.mkdir(parents=True, exist_ok=True)
        with open(path, "w", encoding="utf-8") as f:
            f.write("# Generated by sat-agent\n\n")
            f.write(f"default : {_pyconf_text(spec)}\n")
        return path

    @staticmethod
    def write_application_file(path: Path, application: dict) -> Path:
        """Writes a standalone SAT_SALOME application pyconf file.

        Real application files (e.g. SAT_SALOME/applications/SALOME-9.12.0.pyconf)
        declare a top-level `APPLICATION : { ... }` block only -- products are
        referenced by name in `APPLICATION.products`, not embedded inline.
        """
        path.parent.mkdir(parents=True, exist_ok=True)
        with open(path, "w", encoding="utf-8") as f:
            f.write("# Generated by sat-agent\n\n")
            f.write(f"APPLICATION : {_pyconf_text(application)}\n")
        return path

    @staticmethod
    def set_block_key(path: Path, block_name: str, key: str, value: typing.Any) -> None:
        """Sets (or creates) `key : value` inside a named top-level pyconf
        block (e.g. `properties : { git_server : 'github' }`), by editing
        the file text directly rather than parse-modify-serialize -- this
        works on REAL, hand-authored SAT_SALOME files too (e.g. a shipped
        applications/SALOME-9.16.0-native.pyconf), which PyconfManager's
        exec()-based _load() cannot read at all (see write_product_file's
        docstring). Brace-depth tracking scopes the edit to just this
        block, so it never touches a same-named key elsewhere in the file.
        Creates the block itself (appended at file end) if missing.
        """
        content = path.read_text(encoding="utf-8")
        rendered_value = _pyconf_text(value)

        block_open_re = re.compile(rf"{re.escape(block_name)}\s*:\s*\{{")
        m = block_open_re.search(content)

        if not m:
            addition = f"\n{block_name} :\n{{\n  {key} : {rendered_value}\n}}\n"
            path.write_text(content + addition, encoding="utf-8")
            return

        body_start = m.end()
        depth = 1
        i = body_start
        while i < len(content) and depth > 0:
            if content[i] == "{":
                depth += 1
            elif content[i] == "}":
                depth -= 1
            i += 1
        body_end = i - 1  # index of this block's matching closing '}'

        body = content[body_start:body_end]
        key_re = re.compile(rf"(?m)^([ \t]*){re.escape(key)}\s*:\s*(?:'[^']*'|\"[^\"]*\"|[^\n]*?)\s*$")
        key_match = key_re.search(body)
        if key_match:
            indent = key_match.group(1)
            new_body = body[:key_match.start()] + f"{indent}{key} : {rendered_value}" + body[key_match.end():]
        else:
            new_body = body + f"\n  {key} : {rendered_value}"

        path.write_text(content[:body_start] + new_body + content[body_end:], encoding="utf-8")

    @staticmethod
    def add_to_nested_list(path: Path, block_name: str, key: str, value: str) -> None:
        """Appends value to a list at `<block_name> { <key> : [...] }`
        inside a real pyconf file (e.g. `system_info : { pacman : [...] }`
        in a product file, mirroring the real, shipped `apt`/`apt_dev`/
        `rpm`/`rpm_dev` convention -- see sat_patcher.py:
        ensure_pacman_support), creating the block/key if either is
        missing. Same brace-depth-tracked text splice as set_block_key
        (list-append semantics instead of scalar overwrite); idempotent --
        adding an already-present value is a no-op.
        """
        content = path.read_text(encoding="utf-8")

        block_open_re = re.compile(rf"{re.escape(block_name)}\s*:\s*\{{")
        m = block_open_re.search(content)

        if not m:
            addition = f"\n{block_name} :\n{{\n  {key} : ['{value}']\n}}\n"
            path.write_text(content + addition, encoding="utf-8")
            return

        body_start = m.end()
        depth = 1
        i = body_start
        while i < len(content) and depth > 0:
            if content[i] == "{":
                depth += 1
            elif content[i] == "}":
                depth -= 1
            i += 1
        body_end = i - 1

        body = content[body_start:body_end]
        key_re = re.compile(rf"(?m)^([ \t]*){re.escape(key)}\s*:\s*\[([^\]]*)\]")
        key_match = key_re.search(body)
        if key_match:
            existing = [e.strip().strip("'\"") for e in key_match.group(2).split(",") if e.strip()]
            if value in existing:
                return
            existing.append(value)
            new_list = ", ".join(f"'{e}'" for e in existing)
            indent = key_match.group(1)
            new_body = body[:key_match.start()] + f"{indent}{key} : [{new_list}]" + body[key_match.end():]
        else:
            new_body = body + f"\n  {key} : ['{value}']"

        path.write_text(content[:body_start] + new_body + content[body_end:], encoding="utf-8")

    @staticmethod
    def read_nested_list(path: Path, block_name: str, key: str) -> list[str]:
        """Reads the list at `<block_name> { <key> : [...] }` from a real
        pyconf file -- e.g. `system_info.rpm`/`rpm_dev`, already declared
        for most products since `sat` natively supports RPM-family distros
        (see pkg_search.py: derive_name_from_debian_and_rpm, which uses
        this to cross-reference a product's already-known Debian and RPM
        names without any network call). Read counterpart of
        add_to_nested_list. Returns [] if the file/block/key doesn't exist.
        """
        if not path.exists():
            return []
        content = path.read_text(encoding="utf-8")

        block_open_re = re.compile(rf"{re.escape(block_name)}\s*:\s*\{{")
        m = block_open_re.search(content)
        if not m:
            return []

        body_start = m.end()
        depth = 1
        i = body_start
        while i < len(content) and depth > 0:
            if content[i] == "{":
                depth += 1
            elif content[i] == "}":
                depth -= 1
            i += 1
        body = content[body_start:i - 1]

        key_re = re.compile(rf"(?m)^[ \t]*{re.escape(key)}\s*:\s*\[([^\]]*)\]")
        key_match = key_re.search(body)
        if not key_match:
            return []
        return [e.strip().strip("'\"") for e in key_match.group(1).split(",") if e.strip()]


_SYSTEM_DEPS_DISTRO_RE = re.compile(r"^(\w+)\s*:$")
_SYSTEM_DEPS_ENTRY_RE = re.compile(r"^'([^']*)'\s*:\s*'([^']*)'$")


def read_system_deps_cache(path: Path) -> dict[str, dict[str, str]]:
    """Reads sat-agent's own persisted system-dependency cache
    (`SYSTEM_DEPS : { <distro> : { '<debian_pkg>' : '<resolved_pkg>' ... } }`).

    This file is sat-agent's own memory of package names already confirmed
    by pkg_search.verify_system_package (or accepted from
    DebianPackageTranslator when verification wasn't possible) -- `sat`
    itself never reads it; only write_system_deps_cache below produces it,
    so this reader only needs to handle that fixed, simple shape.
    """
    if not path.exists():
        return {}
    result: dict[str, dict[str, str]] = {}
    current_distro = None
    for raw_line in path.read_text(encoding="utf-8").splitlines():
        line = raw_line.strip()
        if line in ("", "SYSTEM_DEPS :", "{", "}"):
            if line == "}" and current_distro is not None:
                current_distro = None
            continue
        m_distro = _SYSTEM_DEPS_DISTRO_RE.match(line)
        if m_distro:
            current_distro = m_distro.group(1)
            result.setdefault(current_distro, {})
            continue
        m_entry = _SYSTEM_DEPS_ENTRY_RE.match(line)
        if m_entry and current_distro:
            result[current_distro][m_entry.group(1)] = m_entry.group(2)
    return result


def write_system_deps_cache(path: Path, data: dict[str, dict[str, str]]) -> None:
    """Writes the cache read by read_system_deps_cache above (round-trip
    pair, not general pyconf -- see that function's docstring)."""
    lines = [
        "# Generated by sat-agent.",
        "# Cache of system package names verified for a given distro, so",
        "# self-healing doesn't need to re-query/re-guess a package it has",
        "# already resolved. Read/written by sat-agent only -- NOT by `sat`",
        "# itself (see sat_patcher.py for teaching `sat` a new package",
        "# manager natively, which is the mechanism `sat` actually uses).",
        "SYSTEM_DEPS :",
        "{",
    ]
    for distro in sorted(data):
        mapping = data[distro]
        if not mapping:
            continue
        lines.append(f"  {distro} :")
        lines.append("  {")
        for debian_name in sorted(mapping):
            k = debian_name.replace("\\", "\\\\").replace("'", "\\'")
            v = mapping[debian_name].replace("\\", "\\\\").replace("'", "\\'")
            lines.append(f"    '{k}' : '{v}'")
        lines.append("  }")
    lines.append("}")

    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
